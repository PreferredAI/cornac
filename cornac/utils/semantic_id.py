"""Model-neutral Semantic ID catalogs, predictions and item resolvers.

Resolvers select one item from each predicted address bucket for inference or
recommendation evaluation. For example, when items 0 and 1 share an address,
TrainingPopularity([1, 1, 0], num_items=2) selects item 1 from that bucket.
Resolution preserves address order; invalid and repeated addresses leave empty
rank slots. Construct resolver state from training data only.
"""

import hashlib
import json
from abc import ABC, abstractmethod
from collections.abc import Mapping
from dataclasses import dataclass, field
from types import MappingProxyType

import numpy as np


# Catalogs, predictions and replay traces

def _readonly_array(values, dtype, ndim, name):
    original = np.asarray(values)
    if dtype == "int64" and original.size and not np.issubdtype(original.dtype, np.integer):
        raise ValueError(f"{name} must contain integers")
    array = np.array(values, dtype=dtype, order="C", copy=True)
    if array.ndim != ndim:
        raise ValueError(f"{name} must be {ndim}-dimensional")
    return np.frombuffer(array.tobytes(), dtype=array.dtype).reshape(array.shape)


def _freeze_native(value, name="metadata"):
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, Mapping):
        frozen = {}
        for key, item in value.items():
            if not isinstance(key, str):
                raise ValueError(f"{name} keys must be strings")
            frozen[key] = _freeze_native(item, name)
        return MappingProxyType(frozen)
    if isinstance(value, (list, tuple)):
        return tuple(_freeze_native(item, name) for item in value)
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    raise ValueError(f"{name} must contain only Python-native values")


def _thaw_native(value):
    if isinstance(value, Mapping):
        return {key: _thaw_native(item) for key, item in value.items()}
    if isinstance(value, tuple):
        return [_thaw_native(item) for item in value]
    return value


def _validate_cardinalities(cardinalities, width, name):
    if any(isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, np.integer))
           for value in cardinalities):
        raise ValueError(f"{name} must contain integers")
    values = tuple(int(value) for value in cardinalities)
    if len(values) != width:
        raise ValueError(f"{name} must contain one value per SID position")
    if any(value <= 0 for value in values):
        raise ValueError(f"{name} values must be positive")
    return values


def _validate_sid_range(sids, cardinalities, name):
    if sids.size == 0:
        return
    if sids.min() < 0:
        raise ValueError(f"{name} values must be non-negative")
    for position, cardinality in enumerate(cardinalities):
        if sids[:, position].max() >= cardinality:
            raise ValueError(
                f"{name} position {position} contains a value outside "
                f"[0, {cardinality})"
            )


@dataclass(frozen=True, eq=False)
class SemanticIDCatalog:
    """Immutable item-to-SID catalog with an explicit one-to-many reverse map.

    ``tokenizer_sids`` stores the representation before collision suffixing or
    reassignment. ``address_sids`` stores the complete codes generated by the model.
    The two arrays may have different widths.
    """

    item_indices: np.ndarray
    tokenizer_sids: np.ndarray
    address_sids: np.ndarray
    tokenizer_codebook_cardinalities: tuple
    address_codebook_cardinalities: tuple
    mapping_policy: str = "preserve_all"
    metadata: Mapping = field(default_factory=dict)
    _address_to_items: Mapping = field(init=False, repr=False, compare=False)
    _item_to_row: Mapping = field(init=False, repr=False, compare=False)
    _stable_hash: str = field(init=False, repr=False, compare=False)

    def __post_init__(self):
        item_indices = _readonly_array(
            self.item_indices, dtype="int64", ndim=1, name="item_indices"
        )
        tokenizer_sids = _readonly_array(
            self.tokenizer_sids, dtype="int64", ndim=2, name="tokenizer_sids"
        )
        address_sids = _readonly_array(
            self.address_sids, dtype="int64", ndim=2, name="address_sids"
        )
        if tokenizer_sids.shape[0] != len(item_indices):
            raise ValueError("tokenizer_sids must contain one row per item")
        if address_sids.shape[0] != len(item_indices):
            raise ValueError("address_sids must contain one row per item")
        if len(item_indices) == 0:
            raise ValueError("a Semantic-ID catalog must contain at least one item")
        if tokenizer_sids.shape[1] == 0 or address_sids.shape[1] == 0:
            raise ValueError("SID arrays must contain at least one position")
        if len(np.unique(item_indices)) != len(item_indices):
            raise ValueError("item_indices must not contain duplicates")
        if item_indices.size and item_indices.min() < 0:
            raise ValueError("item_indices must be non-negative")

        tokenizer_cardinalities = _validate_cardinalities(
            self.tokenizer_codebook_cardinalities,
            tokenizer_sids.shape[1],
            "tokenizer_codebook_cardinalities",
        )
        address_cardinalities = _validate_cardinalities(
            self.address_codebook_cardinalities,
            address_sids.shape[1],
            "address_codebook_cardinalities",
        )
        _validate_sid_range(tokenizer_sids, tokenizer_cardinalities, "tokenizer_sids")
        _validate_sid_range(address_sids, address_cardinalities, "address_sids")
        if not isinstance(self.mapping_policy, str) or not self.mapping_policy:
            raise ValueError("mapping_policy must be a non-empty string")
        metadata = _freeze_native(self.metadata)

        address_to_items = {}
        item_to_row = {}
        for row, (item_index, address) in enumerate(zip(item_indices, address_sids)):
            key = tuple(int(value) for value in address)
            address_to_items.setdefault(key, []).append(int(item_index))
            item_to_row[int(item_index)] = row
        address_to_items = MappingProxyType(
            {
                address: tuple(sorted(items))
                for address, items in address_to_items.items()
            }
        )

        object.__setattr__(self, "item_indices", item_indices)
        object.__setattr__(self, "tokenizer_sids", tokenizer_sids)
        object.__setattr__(self, "address_sids", address_sids)
        object.__setattr__(
            self, "tokenizer_codebook_cardinalities", tokenizer_cardinalities
        )
        object.__setattr__(
            self, "address_codebook_cardinalities", address_cardinalities
        )
        object.__setattr__(self, "metadata", metadata)
        object.__setattr__(self, "_address_to_items", address_to_items)
        object.__setattr__(self, "_item_to_row", MappingProxyType(item_to_row))
        object.__setattr__(self, "_stable_hash", self._compute_hash())

    def __deepcopy__(self, memo):
        """Reuse this immutable value when a fitted model is copied for saving."""
        memo[id(self)] = self
        return self

    def __reduce__(self):
        """Rebuild proxy-backed state through the validated public constructor."""
        return (
            type(self),
            (
                self.item_indices,
                self.tokenizer_sids,
                self.address_sids,
                self.tokenizer_codebook_cardinalities,
                self.address_codebook_cardinalities,
                self.mapping_policy,
                _thaw_native(self.metadata),
            ),
        )

    @property
    def address_to_items(self):
        """Mapping from generated address SID to sorted global item indices."""
        return self._address_to_items

    @property
    def stable_hash(self):
        """Stable SHA-256 identity of the arrays and catalog policy."""
        return self._stable_hash

    def tokenizer_sid_for_item(self, item_index):
        row = self._item_to_row[int(item_index)]
        return tuple(int(value) for value in self.tokenizer_sids[row])

    def address_sid_for_item(self, item_index):
        row = self._item_to_row[int(item_index)]
        return tuple(int(value) for value in self.address_sids[row])

    def _compute_hash(self):
        digest = hashlib.sha256(b"cornac-semantic-id-catalog-v1\0")
        for name, array in (
            ("item_indices", self.item_indices),
            ("tokenizer_sids", self.tokenizer_sids),
            ("address_sids", self.address_sids),
        ):
            canonical = np.ascontiguousarray(array, dtype="<i8")
            digest.update(name.encode("utf-8") + b"\0")
            digest.update(str(canonical.shape).encode("ascii") + b"\0")
            digest.update(canonical.tobytes())
        payload = {
            "tokenizer_codebook_cardinalities": (self.tokenizer_codebook_cardinalities),
            "address_codebook_cardinalities": self.address_codebook_cardinalities,
            "mapping_policy": self.mapping_policy,
            "metadata": _thaw_native(self.metadata),
        }
        digest.update(
            json.dumps(
                payload,
                sort_keys=True,
                separators=(",", ":"),
                allow_nan=False,
            ).encode("utf-8")
        )
        return digest.hexdigest()


@dataclass(frozen=True, eq=False)
class SemanticIDPrediction:
    """Raw ordered decoder output before SID-to-item resolution."""

    address_sids: np.ndarray
    scores: np.ndarray
    catalog_validity: np.ndarray
    decoder_diagnostics: Mapping = field(default_factory=dict)

    def __reduce__(self):
        return (type(self), (self.address_sids, self.scores, self.catalog_validity,
                             _thaw_native(self.decoder_diagnostics)))

    def __post_init__(self):
        address_sids = _readonly_array(
            self.address_sids, dtype="int64", ndim=2, name="address_sids"
        )
        scores = _readonly_array(self.scores, dtype="float64", ndim=1, name="scores")
        catalog_validity = _readonly_array(
            self.catalog_validity,
            dtype="bool",
            ndim=1,
            name="catalog_validity",
        )
        if len(address_sids) != len(scores) or len(scores) != len(catalog_validity):
            raise ValueError(
                "address_sids, scores, and catalog_validity must have equal length"
            )
        if address_sids.shape[1] == 0:
            raise ValueError("address_sids must contain at least one position")
        object.__setattr__(self, "address_sids", address_sids)
        object.__setattr__(self, "scores", scores)
        object.__setattr__(self, "catalog_validity", catalog_validity)
        object.__setattr__(
            self,
            "decoder_diagnostics",
            _freeze_native(self.decoder_diagnostics, "decoder_diagnostics"),
        )


def prediction_from_catalog_scores(catalog, item_scores, decoder_diagnostics=None):
    """Create an address ranking from architecture-native catalog scores.

    Complete collisions are collapsed by maximum item score. Equal scores are
    ordered lexicographically by address so saved traces are deterministic.
    """
    scores = np.asarray(item_scores, dtype="float64")
    if scores.ndim != 1:
        raise ValueError("item_scores must be one-dimensional")
    if catalog.item_indices.size and catalog.item_indices.max() >= len(scores):
        raise ValueError("item_scores does not cover every catalog item")
    address_scores = {}
    for item_index, address_row in zip(catalog.item_indices, catalog.address_sids):
        address = tuple(int(value) for value in address_row)
        score = float(scores[item_index])
        address_scores[address] = max(address_scores.get(address, -np.inf), score)
    ranked = sorted(address_scores.items(), key=lambda pair: (-pair[1], pair[0]))
    diagnostics = dict(decoder_diagnostics or {})
    diagnostics.update(
        {
            "scored_catalog_items": len(catalog.item_indices),
            "unique_complete_sids": len(ranked),
            "duplicate_catalog_addresses": len(catalog.item_indices) - len(ranked),
            "invalid_sids": 0,
        }
    )
    return SemanticIDPrediction(
        address_sids=np.asarray([address for address, _ in ranked], dtype="int64"),
        scores=np.asarray([score for _, score in ranked], dtype="float64"),
        catalog_validity=np.ones(len(ranked), dtype="bool"),
        decoder_diagnostics=diagnostics,
    )


@dataclass(frozen=True, eq=False)
class SemanticIDTraceRecord:
    """One evaluation query paired with its immutable raw prediction."""

    query_index: int
    user_index: int
    session_index: int
    evaluation_position: int
    history_start_position: int
    history_end_position: int
    target_item_index: int
    target_tokenizer_sid: tuple
    target_address_sid: tuple
    prediction: SemanticIDPrediction

    def __post_init__(self):
        integer_fields = (
            "query_index",
            "user_index",
            "session_index",
            "evaluation_position",
            "history_start_position",
            "history_end_position",
            "target_item_index",
        )
        for name in integer_fields:
            value = getattr(self, name)
            if (isinstance(value, (bool, np.bool_)) or
                    not isinstance(value, (int, np.integer)) or value < 0):
                raise ValueError(f"{name} must be a nonnegative integer")
            object.__setattr__(self, name, int(value))
        if self.query_index < 0 or self.target_item_index < 0:
            raise ValueError("query_index and target_item_index must be non-negative")
        if not 0 <= self.history_start_position <= self.history_end_position:
            raise ValueError("history positions must define a non-negative interval")
        if self.history_end_position != self.evaluation_position:
            raise ValueError(
                "history_end_position must equal the target evaluation_position"
            )
        tokenizer_sid = tuple(int(value) for value in self.target_tokenizer_sid)
        address_sid = tuple(int(value) for value in self.target_address_sid)
        if not tokenizer_sid or not address_sid:
            raise ValueError("target SIDs must not be empty")
        if not isinstance(self.prediction, SemanticIDPrediction):
            raise ValueError("prediction must be a SemanticIDPrediction")
        object.__setattr__(self, "target_tokenizer_sid", tokenizer_sid)
        object.__setattr__(self, "target_address_sid", address_sid)


@dataclass(frozen=True, eq=False)
class SemanticIDTrace:
    """Immutable raw predictions tied to one frozen catalog."""

    catalog_hash: str
    records: tuple
    metadata: Mapping = field(default_factory=dict)

    def __reduce__(self):
        return (type(self), (self.catalog_hash, self.records,
                             _thaw_native(self.metadata)))

    def __post_init__(self):
        records = tuple(self.records)
        if any(not isinstance(record, SemanticIDTraceRecord) for record in records):
            raise ValueError("records must contain SemanticIDTraceRecord instances")
        query_indices = [record.query_index for record in records]
        if len(set(query_indices)) != len(query_indices):
            raise ValueError("query_index must be unique within a trace")
        if not isinstance(self.catalog_hash, str) or not self.catalog_hash:
            raise ValueError("catalog_hash must be a non-empty string")
        object.__setattr__(self, "records", records)
        object.__setattr__(self, "metadata", _freeze_native(self.metadata))


# Item resolution

def _indices(values, name, upper=None):
    values = np.asarray(values)
    if (values.ndim != 1 or (values.size and
            not np.issubdtype(values.dtype, np.integer)) or
            np.any(values < 0) or (upper is not None and np.any(values >= upper))):
        raise ValueError(f"{name} must contain covered nonnegative integer indices")
    return values.astype("int64", copy=False)


def _unit_rows(features):
    features = np.array(features, dtype="float64", copy=True)
    if (features.ndim != 2 or not all(features.shape) or
            not np.all(np.isfinite(features))):
        raise ValueError("features must be a nonempty finite item matrix")
    scales = np.max(np.abs(features), axis=1, keepdims=True)
    np.divide(features, scales, out=features, where=scales != 0)
    norms = np.linalg.norm(features, axis=1, keepdims=True)
    np.divide(features, norms, out=features, where=norms != 0)
    return np.frombuffer(features.tobytes(), dtype=features.dtype).reshape(features.shape)


class SemanticIDResolver(ABC):
    """Score candidate members without targets; highest score wins.

    Implement ``score(query_index, user_index, candidate_items)``. The shared
    operation checks scores and breaks ties by smallest global item index.
    Scores never reorder generated addresses or admit outside candidates.
    """

    @abstractmethod
    def score(self, query_index, user_index, candidate_items):
        """Return one finite score per candidate, in candidate order."""
        raise NotImplementedError

    @property
    def metadata(self):
        return {"resolver": type(self).__name__}


class TrainingPopularity(SemanticIDResolver):
    """Count explicitly supplied training events, retaining repeated events."""

    def __init__(self, training_items, num_items):
        if not isinstance(num_items, (int, np.integer)) or num_items <= 0:
            raise ValueError("num_items must be a positive integer")
        items = _indices(training_items, "training_items", num_items)
        counts = np.bincount(items, minlength=num_items)
        self.counts = np.frombuffer(counts.tobytes(), dtype=counts.dtype)

    def score(self, query_index, user_index, candidate_items):
        return self.counts[list(candidate_items)]

    @property
    def metadata(self):
        return {"resolver": "training_popularity", "source": "training_events",
                "counts_sha256": hashlib.sha256(self.counts.tobytes()).hexdigest()}


class HistoryCosine(SemanticIDResolver):
    """Cosine to normalized sums of normalized training-event item features.

    Rows are global Cornac item indices. Supply training events only; repeats
    contribute repeatedly. A zero user profile ties all members. ``feature_source``
    labels the explicit scoring feature space, which need not be the model's
    tokenizer feature space. No evaluation history or target enters the profile.
    """

    def __init__(self, features, training_users, training_items, num_users,
                 feature_source="provided"):
        self.features = _unit_rows(features)
        if not isinstance(num_users, (int, np.integer)) or num_users <= 0:
            raise ValueError("num_users must be a positive integer")
        users = _indices(training_users, "training_users", num_users)
        items = _indices(training_items, "training_items", len(self.features))
        if users.shape != items.shape:
            raise ValueError("training user/item events must align")
        if not isinstance(feature_source, str) or not feature_source:
            raise ValueError("feature_source must be a nonempty string")
        profiles = np.zeros((num_users, self.features.shape[1]), dtype="float64")
        np.add.at(profiles, users, self.features[items])
        self.profiles = _unit_rows(profiles)
        self.feature_source = feature_source

    def score(self, query_index, user_index, candidate_items):
        if user_index is None or not 0 <= user_index < len(self.profiles):
            raise ValueError("user_index is outside the training profile space")
        return self.features[list(candidate_items)] @ self.profiles[user_index]

    @property
    def metadata(self):
        return {"resolver": "training_history_cosine", "source": "training_events",
                "feature_source": self.feature_source,
                "feature_join": "global_item_index", "zero_profile": "item_index_tie",
                "normalized_features_sha256": hashlib.sha256(self.features.tobytes()).hexdigest()}


class CustomScorer(SemanticIDResolver):
    """Adapt ``callback(query_index, user_index, candidate_items)`` to a resolver."""

    def __init__(self, callback):
        if not callable(callback):
            raise ValueError("callback must be callable")
        self.callback = callback

    def score(self, query_index, user_index, candidate_items):
        return self.callback(query_index, user_index, candidate_items)


def validate_prediction(catalog, prediction):
    """Check raw prediction validity against the admitted frozen catalog."""
    if not isinstance(catalog, SemanticIDCatalog) or not isinstance(prediction, SemanticIDPrediction):
        raise ValueError("expected SemanticIDCatalog and SemanticIDPrediction")
    if prediction.address_sids.shape[1] != catalog.address_sids.shape[1]:
        raise ValueError("prediction address width differs from catalog")
    expected = [tuple(row) in catalog.address_to_items for row in prediction.address_sids]
    if not np.array_equal(prediction.catalog_validity, expected):
        raise ValueError("prediction catalog_validity differs from catalog")


def resolve_semantic_ids(catalog, prediction, resolver, *, user_index=None,
                         query_index=None):
    """Return item/None rank slots from raw predictions for inference or replay.

    Invalid and repeated addresses consume empty slots. Singleton buckets bypass
    scoring. This operation returns no fillers, changes no input, and exposes no
    target to the resolver. Choose a complete-address catalog matching the model.
    """
    validate_prediction(catalog, prediction)
    if not isinstance(resolver, SemanticIDResolver):
        raise ValueError("resolver must be a SemanticIDResolver")
    slots, seen = [], set()
    for row, valid in zip(prediction.address_sids, prediction.catalog_validity):
        address = tuple(int(value) for value in row)
        if not valid or address in seen:
            slots.append(None)
            continue
        seen.add(address)
        items = catalog.address_to_items[address]
        if len(items) == 1:
            slots.append(items[0])
            continue
        scores = np.asarray(resolver.score(query_index, user_index, items), dtype="float64")
        if scores.shape != (len(items),) or not np.all(np.isfinite(scores)):
            raise ValueError("resolver must return one finite score per candidate")
        slots.append(min(zip(items, scores), key=lambda pair: (-pair[1], pair[0]))[0])
    return tuple(slots)
